"""Metrics schema definition using Pydantic"""

from pydantic import BaseModel, Field, field_validator
from typing import List


class MetricDetail(BaseModel):
    """Individual metric with score and notes"""

    score: float = Field(..., ge=0.0, le=5.0)
    max: float = 5.0
    notes: str = ""


class MetricsSchema(BaseModel):
    """Complete metrics schema for code analysis"""

    solid: MetricDetail
    clean_code: MetricDetail
    oop: MetricDetail
    error_handling: MetricDetail
    testing: MetricDetail
    documentation: MetricDetail
    complexity: MetricDetail
    feedback: str = ""
    recommendations: List[str] = []

    @field_validator("recommendations", mode="before")
    @classmethod
    def normalize_recommendations(cls, v):
        if isinstance(v, str):
            return [rec.strip() for rec in v.split(",") if rec.strip()]
        return list(v)


class EnhancedContent(BaseModel):
    """Enhanced report content generated by AI"""

    feedback: str
    recommendations: List[str]
    encouragement: str = ""
